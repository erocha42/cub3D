#include "cub3d.h"

void	minimap(t_game *game)
{
	int	x;
	int	y;

	x = 1700;
	y = 15;
	while (y < 250)
	{
		while (x < 1900)
		{
			my_mlx_pixel_put(game, x, y, game->ceiling_color);
			x++;
		}
		y++;
	}
}